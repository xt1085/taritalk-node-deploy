// taritalk-nodes-submit: two routes that take a node submission and insert it
// as a pending row into D1. POST /submit is the installer's (Feature 7),
// unchanged; POST /web-submit is the website's registration form. Everything
// else is 404 (405 for other methods on a route); nothing is ever listed or
// read back, except that a web attempt repeated with the same request_id is
// answered with the submission ID it already has.
//
// Submissions are schema_version 2: the optional Wallet Query and Base Node
// gRPC endpoints are both URLs of the form https://<domain> (the gRPC
// service runs on TCP 443, which the URL implies), and an optional
// operator_name is a display name and nothing more. A submission without
// one is stored with NULL, never a placeholder: on manual publication it
// means "Community registered". Schema 1 bodies (grpc_address as
// domain:port) are refused; rows stored under schema 1 are kept as they are
// (migration 0002).
//
// The website's route differs where the browser path has to (migration
// 0003): the body carries no network or versions (the row gets 'mainnet' and
// NULLs), the Turnstile token it carries is checked with Cloudflare before
// anything else is spent, only the site's own origins are answered (CORS),
// the observed source IP is used for the rate limit and the Turnstile check
// but never stored, and a request_id generated by the page for one attempt
// is stored with the row, unique: a retry after a lost answer finds the row
// instead of making a second one. Each row records its source, 'tool' or
// 'web'.
//
// Abuse control is one deliberately simple rule: a valid submission attempt
// is accepted once per observed source IP (CF-Connecting-IP) per 60 seconds,
// through the Workers Rate Limiting binding SUBMIT_RATE_LIMIT (wrangler.toml).
// That binding is permissive and local to a Cloudflare location, so this is
// a brake on repetition, not exact accounting. Invalid requests, and web
// requests whose token Cloudflare rejects, are refused before the limit and
// never count against it. Nor does a web retry whose request_id is already
// stored: it is answered from its row, with the token checked but the limit
// untouched, so the page's immediate retry after a lost answer gets its
// submission ID back instead of a 429. Only a new request_id spends the limit.

export const MAX_BODY_BYTES = 4096;
const REQUIRED = ["schema_version", "network", "public_ip", "p2p_port",
  "minotari_version", "installer_version"];
const OPTIONAL = ["wallet_query_url", "grpc_url", "operator_name"];
const WEB_REQUIRED = ["request_id", "turnstile_token", "public_ip", "p2p_port"];
const WEB_OPTIONAL = OPTIONAL;
export const SCHEMA_VERSION = 2;
export const MAX_OPERATOR_NAME_CHARS = 64;
// Turnstile tokens are documented as at most 2048 characters.
const MAX_TURNSTILE_TOKEN_CHARS = 2048;
// The website's origins: the custom domain, the Pages production alias and
// the Pages preview deployments (one label, no deeper).
export const WEB_ORIGINS = ["https://nodes.taritalk.xyz", "https://taritalk-nodes.pages.dev"];
const RE_PREVIEW_ORIGIN = /^https:\/\/[a-z0-9-]+\.taritalk-nodes\.pages\.dev$/;
const TURNSTILE_VERIFY_URL = "https://challenges.cloudflare.com/turnstile/v0/siteverify";
// An operator name: letters, marks, digits, punctuation, symbols and plain
// spaces in any script; no control, format (zero-width, bidi), other
// space, private-use or unassigned character. The installer applies the
// same rule before sending.
const RE_OPERATOR_NAME = /^[\p{L}\p{M}\p{N}\p{P}\p{S} ]+$/u;
const RE_LETTER_OR_DIGIT = /[\p{L}\p{N}]/u;
const RE_RELEASE_VERSION =
  /^(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)(-[0-9A-Za-z]+(\.[0-9A-Za-z]+)*)?$/;
const RE_INSTALLER_VERSION = /^[0-9A-Za-z][0-9A-Za-z.+-]{0,63}$/;
const RE_IPV4 = /^(0|[1-9][0-9]{0,2})\.(0|[1-9][0-9]{0,2})\.(0|[1-9][0-9]{0,2})\.(0|[1-9][0-9]{0,2})$/;
const RE_LABEL = /^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$/;
const RE_SOURCE_IP = /^[0-9A-Fa-f:.]{1,45}$/;
// A lower-case random (version 4) UUID, as crypto.randomUUID() makes them.
const RE_REQUEST_ID = /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/;
const RATE_LIMIT_PERIOD_SECONDS = 60;

// One statement for both routes. request_id is NULL for the installer, and
// NULLs never conflict; a web retry with the same request_id that slips past
// the lookup (two retries in flight at once) changes nothing and is then
// answered from the row it found.
const INSERT = `INSERT INTO submissions (submission_id, submitted_at, source_ip,
  public_ip, p2p_port, network, schema_version, minotari_version,
  installer_version, wallet_query_url, grpc_url, operator_name, review_status,
  source, request_id)
  VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 'pending', ?, ?)
  ON CONFLICT(request_id) DO NOTHING`;
const FIND_BY_REQUEST = "SELECT submission_id FROM submissions WHERE request_id = ?";

function json(status, body, headers = {}) {
  return new Response(JSON.stringify(body), {
    status,
    headers: {
      "content-type": "application/json; charset=utf-8",
      "cache-control": "no-store",
      ...headers,
    },
  });
}

// isPublicIPv4: the same rule as the installer's check_public_ipv4.
export function isPublicIPv4(text) {
  if (typeof text !== "string") return false;
  const m = RE_IPV4.exec(text);
  if (!m) return false;
  const [a, b, c] = [Number(m[1]), Number(m[2]), Number(m[3])];
  const d = Number(m[4]);
  if (a > 255 || b > 255 || c > 255 || d > 255) return false;
  if (a === 0 || a === 10 || a === 127 || a >= 224) return false;
  if (a === 100 && b >= 64 && b <= 127) return false;
  if (a === 169 && b === 254) return false;
  if (a === 172 && b >= 16 && b <= 31) return false;
  if (a === 192 && b === 168) return false;
  if (a === 192 && b === 0 && (c === 0 || c === 2)) return false;
  if (a === 198 && (b === 18 || b === 19)) return false;
  if (a === 198 && b === 51 && c === 100) return false;
  if (a === 203 && b === 0 && c === 113) return false;
  return true;
}

// isDomain: a lower-case DNS host name of at least two labels, the last
// alphabetic, at most 253 characters (the installer's check_domain).
export function isDomain(text) {
  if (typeof text !== "string" || text.length < 4 || text.length > 253) return false;
  const labels = text.split(".");
  if (labels.length < 2 || !labels.every((l) => RE_LABEL.test(l))) return false;
  return /^[a-z]{2,63}$/.test(labels[labels.length - 1]);
}

function isPort(value) {
  return Number.isInteger(value) && value >= 1 && value <= 65535;
}

// isEndpointUrl: https://<domain>, nothing else (no port, path or query).
function isEndpointUrl(text) {
  return typeof text === "string" && text.startsWith("https://") && isDomain(text.slice("https://".length));
}

// isOperatorName: 1 to MAX_OPERATOR_NAME_CHARS characters (code points) of
// RE_OPERATOR_NAME, not starting or ending with a space, with at least one
// letter or digit.
export function isOperatorName(text) {
  if (typeof text !== "string" || text === "" || text.startsWith(" ") || text.endsWith(" ")) return false;
  if ([...text].length > MAX_OPERATOR_NAME_CHARS) return false;
  return RE_OPERATOR_NAME.test(text) && RE_LETTER_OR_DIGIT.test(text);
}

// isWebOrigin: the website's own origins and nothing that merely contains them.
export function isWebOrigin(origin) {
  return typeof origin === "string" && (WEB_ORIGINS.includes(origin) || RE_PREVIEW_ORIGIN.test(origin));
}

// keysOk: every key is known and every required one is present, or the name
// of the first key that is not.
function keysOk(data, required, optional) {
  if (data === null || typeof data !== "object" || Array.isArray(data)) return "body";
  for (const key of Object.keys(data)) {
    if (!required.includes(key) && !optional.includes(key)) return key;
  }
  for (const key of required) {
    if (!(key in data)) return key;
  }
  return null;
}

// optionalFields: the three optional fields, validated, NULL when absent.
function optionalFields(data) {
  let walletQueryUrl = null;
  if ("wallet_query_url" in data) {
    if (!isEndpointUrl(data.wallet_query_url)) return { error: "wallet_query_url" };
    walletQueryUrl = data.wallet_query_url;
  }
  let grpcUrl = null;
  if ("grpc_url" in data) {
    if (!isEndpointUrl(data.grpc_url)) return { error: "grpc_url" };
    grpcUrl = data.grpc_url;
  }
  let operatorName = null;
  if ("operator_name" in data) {
    if (!isOperatorName(data.operator_name)) return { error: "operator_name" };
    operatorName = data.operator_name;
  }
  return { wallet_query_url: walletQueryUrl, grpc_url: grpcUrl, operator_name: operatorName };
}

// validate: the installer submission's fields, or the name of the first bad one.
export function validate(data) {
  const bad = keysOk(data, REQUIRED, OPTIONAL);
  if (bad) return { error: bad };
  if (data.schema_version !== SCHEMA_VERSION) return { error: "schema_version" };
  if (data.network !== "mainnet") return { error: "network" };
  if (!isPublicIPv4(data.public_ip)) return { error: "public_ip" };
  if (!isPort(data.p2p_port)) return { error: "p2p_port" };
  if (typeof data.minotari_version !== "string" || data.minotari_version.length > 64 ||
    !RE_RELEASE_VERSION.test(data.minotari_version)) return { error: "minotari_version" };
  if (typeof data.installer_version !== "string" ||
    !RE_INSTALLER_VERSION.test(data.installer_version)) return { error: "installer_version" };
  const optional = optionalFields(data);
  if (optional.error) return optional;
  return {
    fields: {
      schema_version: SCHEMA_VERSION,
      network: "mainnet",
      public_ip: data.public_ip,
      p2p_port: data.p2p_port,
      minotari_version: data.minotari_version,
      installer_version: data.installer_version,
      ...optional,
    },
  };
}

// validateWeb: the website submission's fields, or the name of the first bad
// one. The network and the versions are not the page's to send.
export function validateWeb(data) {
  const bad = keysOk(data, WEB_REQUIRED, WEB_OPTIONAL);
  if (bad) return { error: bad };
  if (typeof data.request_id !== "string" || !RE_REQUEST_ID.test(data.request_id)) return { error: "request_id" };
  if (typeof data.turnstile_token !== "string" || data.turnstile_token === "" ||
    data.turnstile_token.length > MAX_TURNSTILE_TOKEN_CHARS) return { error: "turnstile_token" };
  if (!isPublicIPv4(data.public_ip)) return { error: "public_ip" };
  if (!isPort(data.p2p_port)) return { error: "p2p_port" };
  const optional = optionalFields(data);
  if (optional.error) return optional;
  return {
    fields: {
      request_id: data.request_id,
      turnstile_token: data.turnstile_token,
      schema_version: SCHEMA_VERSION,
      network: "mainnet",
      public_ip: data.public_ip,
      p2p_port: data.p2p_port,
      minotari_version: null,
      installer_version: null,
      ...optional,
    },
  };
}

// readBody: the request body as text, at most MAX_BODY_BYTES; null if it is
// larger (also when a Content-Length says so) or not UTF-8.
async function readBody(request) {
  const length = request.headers.get("content-length");
  if (length !== null && (!/^[0-9]{1,9}$/.test(length) || Number(length) > MAX_BODY_BYTES)) return null;
  if (!request.body) return "";
  const reader = request.body.getReader();
  const chunks = [];
  let total = 0;
  for (;;) {
    const { done, value } = await reader.read();
    if (done) break;
    total += value.byteLength;
    if (total > MAX_BODY_BYTES) {
      await reader.cancel();
      return null;
    }
    chunks.push(value);
  }
  const bytes = new Uint8Array(total);
  let offset = 0;
  for (const chunk of chunks) {
    bytes.set(chunk, offset);
    offset += chunk.byteLength;
  }
  try {
    return new TextDecoder("utf-8", { fatal: true }).decode(bytes);
  } catch {
    return null;
  }
}

// parseJsonBody: the parsed body, or the response that refuses it.
async function parseJsonBody(request, cors) {
  const type = (request.headers.get("content-type") || "").toLowerCase();
  if (!type.startsWith("application/json")) return { response: json(415, { ok: false, error: "unsupported_media_type" }, cors) };
  const text = await readBody(request);
  if (text === null) return { response: json(413, { ok: false, error: "body_too_large" }, cors) };
  try {
    return { data: JSON.parse(text) };
  } catch {
    return { response: json(400, { ok: false, error: "invalid_json" }, cors) };
  }
}

// sourceIpOf: Cloudflare's observed client address, or null.
function sourceIpOf(request) {
  const header = request.headers.get("cf-connecting-ip");
  return header !== null && RE_SOURCE_IP.test(header) ? header : null;
}

// rateLimited: one accepted attempt per observed source per period. A
// request whose source cannot be read shares one key, so it cannot be used
// to bypass. Returns the refusing response, or null to go on.
async function rateLimited(env, sourceIp, cors) {
  let allowed;
  try {
    allowed = (await env.SUBMIT_RATE_LIMIT.limit({ key: sourceIp ?? "unknown" })).success === true;
  } catch {
    return json(500, { ok: false, error: "rate_limit_error" }, cors);
  }
  if (allowed) return null;
  return json(429, { ok: false, error: "rate_limited" }, { ...cors, "retry-after": String(RATE_LIMIT_PERIOD_SECONDS) });
}

// verifyTurnstile: asks Cloudflare whether the token is good. "ok" when it
// is; "failed" when Cloudflare says no; "unavailable" when Cloudflare could
// not be asked or did not answer sensibly. The token and the IP go to
// Cloudflare only.
async function verifyTurnstile(token, sourceIp, secret, fetchImpl) {
  const body = new URLSearchParams({ secret, response: token });
  if (sourceIp !== null) body.set("remoteip", sourceIp);
  let answer;
  try {
    const response = await fetchImpl(TURNSTILE_VERIFY_URL, { method: "POST", body });
    if (!response.ok) return "unavailable";
    answer = await response.json();
  } catch {
    return "unavailable";
  }
  if (answer === null || typeof answer !== "object") return "unavailable";
  return answer.success === true ? "ok" : "failed";
}

// findByRequest: the submission ID already stored for a web request_id, null
// when there is none, or undefined on a storage failure.
async function findByRequest(env, requestId) {
  try {
    const found = await env.DB.prepare(FIND_BY_REQUEST).bind(requestId).first();
    if (found === null) return null;
    return typeof found?.submission_id === "string" ? found.submission_id : undefined;
  } catch {
    return undefined;
  }
}

// insertSubmission: the row, or null on a storage failure. A web retry that
// conflicts on request_id is answered with the ID the first attempt got.
async function insertSubmission(env, f, sourceIp, source, requestId) {
  const submissionId = crypto.randomUUID();
  try {
    const result = await env.DB.prepare(INSERT).bind(submissionId, new Date().toISOString(), sourceIp,
      f.public_ip, f.p2p_port, f.network, f.schema_version, f.minotari_version,
      f.installer_version, f.wallet_query_url, f.grpc_url, f.operator_name, source, requestId).run();
    if (requestId !== null && result?.meta?.changes === 0) return (await findByRequest(env, requestId)) ?? null;
  } catch {
    return null;
  }
  return submissionId;
}

// handleSubmit: POST /submit, the installer's route.
async function handleSubmit(request, env) {
  if (request.method !== "POST") {
    return json(405, { ok: false, error: "method_not_allowed" }, { allow: "POST" });
  }
  const parsed = await parseJsonBody(request, {});
  if (parsed.response) return parsed.response;
  const checked = validate(parsed.data);
  if (checked.error) return json(400, { ok: false, error: "invalid_field", field: checked.error });
  const sourceIp = sourceIpOf(request);
  const limited = await rateLimited(env, sourceIp, {});
  if (limited) return limited;
  const submissionId = await insertSubmission(env, checked.fields, sourceIp, "tool", null);
  if (submissionId === null) return json(500, { ok: false, error: "storage_error" });
  return json(200, { ok: true, submission_id: submissionId, status: "pending" });
}

// handleWebSubmit: POST /web-submit, the website's route, and its preflight.
async function handleWebSubmit(request, env, fetchImpl) {
  const origin = request.headers.get("origin");
  const allowedOrigin = isWebOrigin(origin);
  const cors = allowedOrigin ? { "access-control-allow-origin": origin, vary: "origin" } : {};
  if (request.method === "OPTIONS") {
    if (!allowedOrigin) return json(403, { ok: false, error: "origin_not_allowed" });
    return new Response(null, {
      status: 204,
      headers: {
        ...cors,
        "access-control-allow-methods": "POST, OPTIONS",
        "access-control-allow-headers": "content-type",
        "access-control-max-age": "86400",
      },
    });
  }
  if (request.method !== "POST") {
    return json(405, { ok: false, error: "method_not_allowed" }, { ...cors, allow: "POST, OPTIONS" });
  }
  if (!allowedOrigin) return json(403, { ok: false, error: "origin_not_allowed" });
  const parsed = await parseJsonBody(request, cors);
  if (parsed.response) return parsed.response;
  const checked = validateWeb(parsed.data);
  if (checked.error) return json(400, { ok: false, error: "invalid_field", field: checked.error }, cors);
  const f = checked.fields;
  if (typeof env.TURNSTILE_SECRET !== "string" || env.TURNSTILE_SECRET === "") {
    return json(500, { ok: false, error: "server_error" }, cors);
  }
  const sourceIp = sourceIpOf(request);
  const verdict = await verifyTurnstile(f.turnstile_token, sourceIp, env.TURNSTILE_SECRET, fetchImpl);
  if (verdict === "failed") return json(403, { ok: false, error: "turnstile_failed" }, cors);
  if (verdict !== "ok") return json(502, { ok: false, error: "turnstile_unavailable" }, cors);
  // A retry of an attempt that is already stored (its answer was lost) gets
  // the same answer again, before the rate limit, which only a new attempt spends.
  const existing = await findByRequest(env, f.request_id);
  if (existing === undefined) return json(500, { ok: false, error: "storage_error" }, cors);
  if (existing !== null) return json(200, { ok: true, submission_id: existing, status: "pending" }, cors);
  const limited = await rateLimited(env, sourceIp, cors);
  if (limited) return limited;
  // The source IP served the rate limit and the Turnstile check; the row gets none.
  const submissionId = await insertSubmission(env, f, null, "web", f.request_id);
  if (submissionId === null) return json(500, { ok: false, error: "storage_error" }, cors);
  return json(200, { ok: true, submission_id: submissionId, status: "pending" }, cors);
}

export async function handleRequest(request, env, deps = {}) {
  const url = new URL(request.url);
  if (url.pathname === "/submit") return handleSubmit(request, env);
  if (url.pathname === "/web-submit") return handleWebSubmit(request, env, deps.fetch ?? globalThis.fetch);
  return json(404, { ok: false, error: "not_found" });
}

export default {
  async fetch(request, env) {
    return handleRequest(request, env);
  },
};
